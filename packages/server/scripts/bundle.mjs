// Produce the self-host single-file bundle that the Docker image runs.
//
// esbuild bundles a composition entry (default: examples/serve.mjs) and the
// `@dwk` packages it pulls in into one ESM file, aliasing `cloudflare:workers`
// to the Node Durable-Object shim at build time — so the bundle needs no
// `module.register` loader hook at runtime.
//
//   node scripts/bundle.mjs [entry] [outfile]
//
// @see spec/self-hosting.md §10
import { build } from "esbuild";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = process.argv[2] ?? resolve(pkgRoot, "examples/serve.mjs");
const outfile =
  process.argv[3] ?? resolve(pkgRoot, "dist-bundle/dwk-serve.mjs");

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  // The reason this bundle exists: replace the workerd `cloudflare:workers`
  // module with the Node shim, so the DO packages run with no loader hook.
  alias: {
    "cloudflare:workers": resolve(pkgRoot, "dist/cloudflare-workers.js"),
  },
  // `ws` loads these native accelerators optionally; keep them external so the
  // bundle runs on the pure-JS fallback when they are not installed.
  external: ["bufferutil", "utf-8-validate"],
  banner: {
    // Give the ESM output a real `require` so esbuild's interop shim can load
    // node builtins that bundled CommonJS deps (express) require dynamically.
    js: [
      "#!/usr/bin/env node",
      "// @dwk/server self-host bundle (generated by scripts/bundle.mjs)",
      'import { createRequire as __dwkCreateRequire } from "node:module";',
      "const require = __dwkCreateRequire(import.meta.url);",
    ].join("\n"),
  },
  logLevel: "warning",
});

console.log(`bundled ${entry} -> ${outfile}`);
